/**
 * Dynamically composes the authentic Sahih Al-Bukhari Istikhara Dua with the user's
 * specific matter inserted in both prophetic positions ("هذا الأمر [...]").
 */
export function composeIstikharaDuaWithMatter(rawMatterAr: string): ComposedIstikharaDuaResult {
  const cleanMatter = rawMatterAr.trim();
  const displayMatter = cleanMatter.length > 0 ? cleanMatter : 'تُسمِّي حاجتكَ هُنا';

  const introTextAr =
    'اللَّهُمَّ إِنِّي أَسْتَخِيرُكَ بِعِلْمِكَ، وَأَسْتَقْدِرُكَ بِقُدْرَتِكَ، وَأَسْأَلُكَ مِنْ فَضْلِكَ العَظِيمِ؛ فَإِنَّكَ تَقْدِرُ وَلَا أَقْدِرُ، وَتَعْلَمُ وَلَا أَعْلَمُ، وَأَنْتَ عَلَّامُ الغُيُوبِ.';

  const firstClauseBeforeMatterAr = 'اللَّهُمَّ إِنْ كُنْتَ تَعْلَمُ أَنَّ هَذَا الأَمْرَ';
  const firstClauseAfterMatterAr =
    'خَيْرٌ لِي فِي دِينِي وَمَعَاشِي وَعَاقِبَةِ أَمْرِي - وَعَاجِلِ أَمْرِي وَآجِلِهِ - فَاقْدُرْهُ لِي وَيَسِّرْهُ لِي ثُمَّ بَارِكْ لِي فِيهِ،';

  const secondClauseBeforeMatterAr = 'وَإِنْ كُنْتَ تَعْلَمُ أَنَّ هَذَا الأَمْرَ';
  const secondClauseAfterMatterAr =
    'شَرٌّ لِي فِي دِينِي وَمَعَاشِي وَعَاقِبَةِ أَمْرِي - وَعَاجِلِ أَمْرِي وَآجِلِهِ - فَاصْرِفْهُ عَنِّي وَاصْرِفْنِي عَنْهُ، وَاقْدُرْ لِيَ الخَيْرَ حَيْثُ كَانَ ثُمَّ أَرْضِنِي بِهِ.';

  const fullFormattedDuaAr = `${introTextAr} ${firstClauseBeforeMatterAr} (${displayMatter}) ${firstClauseAfterMatterAr} ${secondClauseBeforeMatterAr} (${displayMatter}) ${secondClauseAfterMatterAr}`;

  return {
    matterAr: displayMatter,
    introTextAr,
    firstClauseBeforeMatterAr,
    firstClauseAfterMatterAr,
    secondClauseBeforeMatterAr,
    secondClauseAfterMatterAr,
    fullFormattedDuaAr,
  };
}

