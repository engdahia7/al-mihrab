export function loadIstikharaJournalEntries(): IstikharaJournalEntry[] {
  if (typeof window === 'undefined') return [];
  try {
    const raw = localStorage.getItem(ISTIKHARA_JOURNAL_STORAGE_KEY);
    if (!raw) return [];
    const parsed = JSON.parse(raw);
    return Array.isArray(parsed) ? parsed : [];
  } catch {
    return [];
  }
}

export function saveIstikharaJournalEntries(entries: IstikharaJournalEntry[]): void {
  if (typeof window === 'undefined') return;
  try {
    localStorage.setItem(ISTIKHARA_JOURNAL_STORAGE_KEY, JSON.stringify(entries));
  } catch {
    // ignore
  }
}

export function addIstikharaJournalEntry(
  entries: IstikharaJournalEntry[],
  matterAr: string,
  consultationNotesAr: string,
  dateISO: string
): IstikharaJournalEntry[] {
  const cleanMatter = matterAr.trim();
  if (!cleanMatter) return entries;
  const newEntry: IstikharaJournalEntry = {
    id: `istikhara-${Date.now()}-${Math.random().toString(36).slice(2, 7)}`,
    matterAr: cleanMatter,
    dateISO,
    consultationNotesAr: consultationNotesAr.trim(),
    status: 'pending_tawakkul',
  };
  return [newEntry, ...entries];
}

export function updateIstikharaJournalStatus(
  entries: IstikharaJournalEntry[],
  entryId: string,
  nextStatus: IstikharaDecisionStatus
): IstikharaJournalEntry[] {
  return entries.map((entry) =>
    entry.id === entryId ? { ...entry, status: nextStatus } : entry
  );
}

export function deleteIstikharaJournalEntry(
  entries: IstikharaJournalEntry[],
  entryId: string
): IstikharaJournalEntry[] {
  return entries.filter((entry) => entry.id !== entryId);
}

