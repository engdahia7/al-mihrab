// Audio URL builder for Prophet Quranic Duas (EveryAyah Alafasy + Husary fallback)
export function getProphetDuaAudioUrls(surahNumber: number, ayahNumber: number): string[] {
  const sss = String(surahNumber).padStart(3, '0');
  const aaa = String(ayahNumber).padStart(3, '0');
  return [
    `https://everyayah.com/data/Alafasy_128kbps/${sss}${aaa}.mp3`,
    `https://everyayah.com/data/Husary_128kbps/${sss}${aaa}.mp3`,
    `https://everyayah.com/data/Alafasy_64kbps/${sss}${aaa}.mp3`,
  ];
}

// LocalStorage Persistence for Prophet Stories Reflection Progress
const PROPHETS_REFLECTION_STORAGE_KEY = 'almihrab_prophets_reflected_v1';

export function loadReflectedProphetIds(): string[] {
  if (typeof window === 'undefined') return [];
  try {
    const raw = localStorage.getItem(PROPHETS_REFLECTION_STORAGE_KEY);
    if (!raw) return [];
    const parsed = JSON.parse(raw);
    return Array.isArray(parsed) ? parsed : [];
  } catch {
    return [];
  }
}

export function saveReflectedProphetIds(ids: string[]): void {
  if (typeof window === 'undefined') return;
  try {
    localStorage.setItem(PROPHETS_REFLECTION_STORAGE_KEY, JSON.stringify(ids));
  } catch {
    // ignore
  }
}

export function toggleProphetReflected(currentIds: string[], prophetId: string): string[] {
  if (currentIds.includes(prophetId)) {
    return currentIds.filter((id) => id !== prophetId);
  }
  return [...currentIds, prophetId];
}

