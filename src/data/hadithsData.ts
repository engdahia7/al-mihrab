/**
 * Searches authentic hadiths by Arabic text (diacritic-free), topic, narrator, or source/takhrij.
 */
export function searchAuthenticHadiths(
  query: string,
  topicId: HadithTopicId = 'all'
): AuthenticHadithItem[] {
  const normQuery = normalizeArabicForQuranSearch(query);
  return AUTHENTIC_HADITHS_LIST.filter((item) => {
    if (topicId !== 'all' && item.topicId !== topicId) {
      return false;
    }
    if (!normQuery) return true;

    const haystack = normalizeArabicForQuranSearch(
      `${item.titleAr} ${item.topicLabelAr} ${item.hadithArabicText} ${item.narratorAr} ${item.narratorBioBriefAr} ${item.takhrijAr} ${item.gradingAr} ${item.fiqhBenefitAr} ${item.keywords.join(' ')}`
    );
    return haystack.includes(normQuery);
  });
}
